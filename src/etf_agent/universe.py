def is_valid_ticker(ticker: str) -> bool:
    """檢查股票代號是否屬於官方 150 檔白名單。"""
    return ticker in UNIVERSE_150


def get_authority(ticker: str) -> str:
    """取得該股票在 D-Plan sources 中對應的 authority ('twse' 或 'tpex')。"""
    meta = UNIVERSE_150.get(ticker)
    if meta is None:
        raise KeyError(f"股票代號 {ticker!r} 不在官方 150 檔白名單中！")
    return meta.market


def get_max_weight(ticker: str) -> float:
    """取得該股票的單一持股權重上限 (2330 為 0.25，其餘為 0.10)。"""
    meta = UNIVERSE_150.get(ticker)
    if meta is None:
        raise KeyError(f"股票代號 {ticker!r} 不在官方 150 檔白名單中！")
    return meta.max_weight


def compute_active_share(agent_weights: dict[str, float], benchmark_weights: dict[str, float]) -> float:
    """依官方公式 (RULE-POR-07) 計算前 15 大持股之 Active Share = 0.5 * sum(|W_agent - W_bench|)。"""
    top15_agent = dict(sorted(agent_weights.items(), key=lambda x: x[1], reverse=True)[:15])
    top15_bench = dict(sorted(benchmark_weights.items(), key=lambda x: x[1], reverse=True)[:15])
    all_tickers = set(top15_agent.keys()) | set(top15_bench.keys())
    diff_sum = sum(abs(top15_agent.get(t, 0.0) - top15_bench.get(t, 0.0)) for t in all_tickers)
    return 0.5 * diff_sum
